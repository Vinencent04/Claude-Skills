import React from "react";
import { Composition, registerRoot } from "remotion";
import { KitchenShort, KITCHEN_FRAMES } from "./videos/kitchen/Kitchen";
import { RevoShort, REVO_FRAMES } from "./videos/revo/Revo";
import { BeerfloodShort, BEERFLOOD_FRAMES } from "./videos/beerflood/Beerflood";
import { TeapartyShort, TEAPARTY_FRAMES } from "./videos/teaparty/Teaparty";
import { EmuwarShort, EMUWAR_FRAMES } from "./videos/emuwar/Emuwar";
import { CadaverShort, CADAVER_FRAMES } from "./videos/cadaver/Cadaver";
import { Subs, SUBS_FRAMES } from "./videos/subs/Subs";
import { SubsBeerflood, SUBS_BF_FRAMES } from "./videos/subs/SubsBeerflood";
